import { readFile } from "node:fs/promises";
import { verifyReviewedSource } from "./security-review-source.mjs";
import { reviewSchema, verifyReview } from "./security-review-contract.mjs";
const index = process.argv.indexOf("--release");
const release = (index >= 0 ? process.argv[index + 1] : undefined) || process.env.GITHUB_REF_NAME;
if (!release?.match(/^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/u)) throw new Error("Pass --release vX.Y.Z.");
const packageJson = JSON.parse(await readFile("package.json", "utf8"));
if (release !== `v${packageJson.version}`) throw new Error("Security review release does not match package version.");
const attestationPath = `security-reviews/${release}.review.json`;
const attestation = reviewSchema.parse(JSON.parse(await readFile(attestationPath, "utf8")));
const registry = JSON.parse(await readFile("security-reviews/trusted-reviewers.json", "utf8"));
const reportBytes = await readFile(attestation.reportPath);
const review = verifyReview({ attestation, registry, release, reportBytes });
verifyReviewedSource(review);
process.stdout.write(`Independent security review verified for ${release}, source ${review.sourceCommit}.\n`);
